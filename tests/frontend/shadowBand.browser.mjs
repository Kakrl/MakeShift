import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const require = createRequire(new URL("../../frontend/package.json", import.meta.url));
const { chromium } = require("playwright");
const output = path.join(root, "frontend/test-results/shadow-band");
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: process.env.CV_BROWSER_CHANNEL || "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; const inferenceRequests = [];
  page.on("pageerror", (e) => errors.push(e.message));
  page.on("request", (r) => { if (/mediapipe|opencv|hand_landmarker/.test(r.url())) inferenceRequests.push(r.url()); });
  await page.goto(`${process.env.MAKE_SHIFT_URL || "http://127.0.0.1:3107"}/cv-shadow-test`);
  const fixtures = await page.evaluate(() => {
    const c = document.createElement("canvas"); c.width = 640; c.height = 427;
    const ctx = c.getContext("2d"); ctx.fillStyle = "rgb(200,200,200)"; ctx.fillRect(0, 0, c.width, c.height);
    const reference = c.toDataURL().split(",")[1];
    ctx.fillStyle = "rgb(100,100,100)"; ctx.fillRect(298, 201, 5, 5);
    return { reference, current: c.toDataURL().split(",")[1] };
  });
  const upload = (id, name, data) => page.locator(id).setInputFiles({ name, mimeType: "image/png", buffer: Buffer.from(data, "base64") });
  await upload("#heatmap-reference", "band-reference.png", fixtures.reference);
  await upload("#heatmap-source", "band-five-pixels.png", fixtures.current);
  await page.waitForFunction(() => document.querySelector('[role="status"]')?.textContent?.startsWith("Heatmaps ready."));
  await page.getByLabel("Exclusion method", { exact: true }).selectOption("projection");
  await page.getByLabel("Maximum retained e_I", { exact: true }).fill("0.12");
  const band = page.getByRole("region", { name: "Fingertip shadow band" });
  assert(await band.getByRole("button", { name: "Save band measurement", exact: true }).isDisabled());
  for (const [label, value] of [["Tip X", 300], ["Tip Y", 200], ["Outward X", 300], ["Outward Y", 220]]) await band.getByLabel(label, { exact: true }).fill(String(value));
  await band.getByRole("button", { name: "Confirm anchors for this frame", exact: true }).click();
  assert.match(await band.getByTestId("band-readout").innerText(), /Median band 5 analysis px; 5\/5/);
  await band.getByLabel("Band finger", { exact: true }).selectOption("index");
  await band.getByLabel("Band phase", { exact: true }).selectOption("hover");
  await band.getByRole("button", { name: "Save band measurement", exact: true }).click();
  await band.getByLabel("Tip X", { exact: true }).fill("-1");
  await band.getByRole("button", { name: "Confirm anchors for this frame", exact: true }).click();
  assert.match(await band.getByTestId("band-readout").innerText(), /Invalid anchors/);
  assert(await band.getByRole("button", { name: "Save band measurement", exact: true }).isDisabled());
  // Click-based two-anchor interaction: tip alone must not authorize saving.
  await band.getByRole("button", { name: "Mark fingertip", exact: true }).click();
  const source = page.locator("#band-source"); const rect = await source.boundingBox();
  await source.click({ position: { x: 300 / 640 * rect.width, y: 200 / 427 * rect.height } });
  assert(await band.getByRole("button", { name: "Save band measurement", exact: true }).isDisabled());
  await source.click({ position: { x: 300 / 640 * rect.width, y: 220 / 427 * rect.height } });
  assert.match(await band.getByTestId("band-readout").innerText(), /Median band 5/);
  await upload("#heatmap-source", "empty-paper.png", fixtures.reference);
  await page.waitForFunction(() => document.querySelector('[role="status"]')?.textContent?.startsWith("Heatmaps ready.") && [...document.querySelectorAll("p")].some((p) => p.textContent === "empty-paper.png"));
  assert(await band.getByRole("button", { name: "Save band measurement", exact: true }).isDisabled(), "New frame needs confirmation");
  await band.getByRole("button", { name: "Confirm anchors for this frame", exact: true }).click();
  assert.match(await band.getByTestId("band-readout").innerText(), /Insufficient evidence/);
  await band.getByRole("button", { name: "Save band measurement", exact: true }).click();
  const pending = page.waitForEvent("download");
  await band.getByRole("button", { name: "Export band JSON", exact: true }).click();
  const download = await pending; const exported = path.join(output, "browser-measurements.json"); await download.saveAs(exported);
  const result = JSON.parse(await readFile(exported, "utf8"));
  assert.equal(result.schemaVersion, 1); assert.equal(result.records.length, 2);
  assert.equal(result.records[0].measurement.medianWidth, 5);
  assert.equal(result.records[0].context.source.name, "band-five-pixels.png");
  assert.equal(result.records[0].measurement.rays[0].profile.length, 24);
  assert.equal(result.records[1].measurement.medianWidth, null);
  assert.equal(result.records[1].measurement.status, "insufficient-evidence");
  await band.getByRole("button", { name: "Remove last band record", exact: true }).click();
  assert.match(await band.getByTestId("band-count").innerText(), /^1 \/ 200/);
  await band.scrollIntoViewIfNeeded(); await page.screenshot({ path: path.join(output, "desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Mobile overflow");
  await band.scrollIntoViewIfNeeded(); await page.screenshot({ path: path.join(output, "mobile.png") });
  assert.deepEqual(errors, []); assert.deepEqual(inferenceRequests, []);
  await writeFile(path.join(output, "browser-report.json"), JSON.stringify({ numericalBand: "passed", unavailableAndFrameGuard: "passed", clickAndKeyboardAnchors: "passed", exportSnapshotsAndRemoval: "passed", mobile: "passed", errors, inferenceRequests }, null, 2));
  process.stdout.write(`PASS: shadow-band UI, numerical width, unknown states, anchors, export and mobile. ${output}\n`);
} finally { await browser.close(); }
